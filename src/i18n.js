function interpolate(str, vars) {
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars && k in vars ? String(vars[k]) : m));
}

export function translate(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS[DEFAULT_LANG];
  let value = dict[key] ?? STRINGS.en[key] ?? key;
  if (value && typeof value === 'object') {
    const category = new Intl.PluralRules(lang).select(Number(vars?.n ?? 0));
    value = value[category] ?? value.other;
  }
  return interpolate(value, vars);
}

export function exerciseText(lang, key, ex) {
  const entry = (STRINGS[lang] || STRINGS[DEFAULT_LANG]).exercises?.[key];
  return {
    label: entry?.label ?? ex?.label ?? key,
    description: entry?.description ?? ex?.description ?? '',
  };
}
