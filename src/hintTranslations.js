export function localizeHint(hint, lang) {
  if (lang === 'en') return hint;
  const index = LANG_INDEX[lang];
  if (index === undefined) return hint;
  if (HINTS[hint]) return HINTS[hint][index];

  const parts = hint.split(' → ');
  if (parts.length === 2 && HINTS[parts[0]] && QUALIFIERS[parts[1]]) {
    const subject = parts[0] === 'her'
      ? ['ona', 'ona', 'вона', 'она'][index]
      : HINTS[parts[0]][index];
    return `${subject} → ${QUALIFIERS[parts[1]][index]}`;
  }
  return hint;
}
